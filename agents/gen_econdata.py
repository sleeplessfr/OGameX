#!/usr/bin/env python3
"""Writes swarm/econdata.py: the price and requirement tables of the game, read from the game's own PHP source.

    python gen_econdata.py                 (reads ../app/GameObjects, writes swarm/econdata.py)
    python gen_econdata.py --check         (exit 1 when the committed file differs from the PHP source)

The economy simulator (swarm/econsim.py) uses these tables, so it can never drift from the game unnoticed: the test
tests/test_econdata.py runs the --check whenever the PHP source is next to the agents folder.
"""
from __future__ import annotations

import argparse
import pprint
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCES = {"building": "BuildingObjects.php", "station": "StationObjects.php", "research": "ResearchObjects.php"}
NAME = re.compile(r"->machine_name\s*=\s*'([a-z_]+)'")
PRICE = re.compile(r"new GameObjectPrice\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.]+)\s*(?:,\s*(true|false))?\s*\)")
REQ = re.compile(r"new GameObjectRequirement\(\s*'([a-z_]+)'\s*,\s*(\d+)\s*\)")


def parse(text: str, kind: str) -> dict[str, dict]:
    out: dict[str, dict] = {}
    marks = [(m.start(), m.group(1)) for m in NAME.finditer(text)]
    for i, (pos, name) in enumerate(marks):
        end = marks[i + 1][0] if i + 1 < len(marks) else len(text)
        block = text[pos:end]
        price = PRICE.search(block)
        if not price:
            continue
        m, c, d, e, f, rnd = price.groups()
        reqs = {}
        if "->requirements" in block:
            part = block[block.index("->requirements"):]
            part = part[:part.index("];")] if "];" in part else part
            reqs = {n: int(v) for n, v in REQ.findall(part)}
        out[name] = {"kind": kind, "metal": int(m), "crystal": int(c), "deuterium": int(d), "energy": int(e),
                     "factor": float(f), "round100": rnd == "true", "requires": reqs}
    return out


def build(src: Path) -> dict[str, dict]:
    data: dict[str, dict] = {}
    for kind, fname in SOURCES.items():
        data.update(parse((src / fname).read_text(encoding="utf-8"), kind))
    return data


def render(data: dict[str, dict]) -> str:
    body = pprint.pformat(data, width=140, sort_dicts=True)
    return ('"""Price and requirement tables of the game. GENERATED by gen_econdata.py from app/GameObjects/*.php: do not edit by hand."""\n'
            f"OBJECTS = {body}\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--src", default=str(HERE.parent / "app" / "GameObjects"))
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    src, target = Path(args.src), HERE / "swarm" / "econdata.py"
    if not src.is_dir():
        print(f"game source not found at {src}")
        return 2
    text = render(build(src))
    if args.check:
        same = target.exists() and target.read_text(encoding="utf-8") == text
        print("econdata.py is up to date" if same else "econdata.py differs from the PHP source: run gen_econdata.py")
        return 0 if same else 1
    target.write_text(text, encoding="utf-8")
    print(f"wrote {target} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
